#!/usr/bin/env python3
"""Build uncertain-log.md: every `<!-- ... -->` comment in the page files that records doubt or a layout
oddity, by image (the 'per-page log' of transcription-notes.md section 5), with the comma/period doubts
and the worn-letter doubts grouped first. Standard library only.

Usage:  python3 tools/make_uncertain_log.py [--out FILE]
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default=str(ROOT / 'uncertain-log.md'))
    args = ap.parse_args()
    unc, lay = [], []
    for f in sorted((ROOT / 'book-of-mormon-1841-pages').glob('page-*.md')):
        n = int(f.stem[-3:])
        t = f.read_text(encoding='utf-8')
        for m in re.finditer(r'<!--\s*(.*?)\s*-->', t, flags=re.S):
            c = re.sub(r'\s+', ' ', m.group(1))
            if re.match(r'image \d+$', c) or c == 'cont':
                continue
            (unc if c.startswith('uncertain') else lay).append((n, c))
    punct = [(n, c) for n, c in unc if re.search(r'comma|period|colon|semicolon|space', c, re.I)]
    other = [(n, c) for n, c in unc if (n, c) not in punct]
    out = ["# Uncertain readings and layout comments, by PDF page",
           "",
           "Generated by `tools/make_uncertain_log.py` from the page files (so it stays current). `uncertain` comments are doubtful readings "
           "that were written as shown; layout comments describe what is printed (ornaments, missing running heads, bleed-through, odd folios). "
           "Image numbers are PDF page numbers; printed folio = PDF page - 8.",
           "",
           "**Where to see the original.** Numbers are pages of the scan PDF (Book-of-Mormon-1841.pdf, 656 pages). "
           "No images are included in this repository.",
           "",
           f"## Doubtful punctuation and spacing ({len(punct)})", ""]
    out += [f"- **{n}**: {c}" for n, c in punct]
    out += ["", f"## Other doubtful readings: worn type, blots, joins ({len(other)})", ""]
    out += [f"- **{n}**: {c}" for n, c in other]
    out += ["", f"## Layout and printing comments ({len(lay)})", ""]
    out += [f"- **{n}**: {c}" for n, c in lay]
    Path(args.out).write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{len(punct)} punctuation + {len(other)} other doubtful + {len(lay)} layout comments -> {args.out}')


if __name__ == '__main__':
    main()
